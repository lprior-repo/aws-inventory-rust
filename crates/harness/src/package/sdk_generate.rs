//! Deterministic generation of the SDK catalog crate from the snapshot.

use std::collections::BTreeSet;
use std::io::{self, Write};
use std::path::{Path, PathBuf};

use serde_json::Value;

use crate::HarnessError;

/// Files generated for the catalog crate, in Python's output order.
pub fn outputs(
    destination: &Path,
    document: &Value,
) -> Result<Vec<(PathBuf, String)>, HarnessError> {
    let services = services(document)?;
    let mut generated = Vec::with_capacity(services.len().saturating_add(2));
    generated.push((destination.join("Cargo.toml"), cargo_manifest(services)?));
    generated.push((
        destination.join("src").join("lib.rs"),
        library(document, services)?,
    ));
    let letters = first_letters(services)?;
    for letter in letters {
        let path = destination
            .join("src")
            .join(format!("services_{letter}.rs"));
        generated.push((path, service_library(letter, services)?));
    }
    Ok(generated)
}

/// Write one generated file through the shared exclusive atomic-file writer.
pub fn write(path: &Path, text: &str) -> Result<(), HarnessError> {
    catalog_tool::package::atomic_write(path, |file| {
        file.write_all(text.as_bytes())?;
        Ok(())
    })
    .map_err(|error| match error.downcast::<io::Error>() {
        Ok(error) => HarnessError::Io(*error),
        Err(error) => HarnessError::invalid(error.to_string()),
    })
}

/// Snapshot services array, already validated by the caller.
fn services(document: &Value) -> Result<&[Value], HarnessError> {
    document
        .get("services")
        .and_then(Value::as_array)
        .map(Vec::as_slice)
        .ok_or_else(|| HarnessError::invalid("invalid service list"))
}

/// Read a required string field from a service.
fn field<'a>(service: &'a Value, name: &str) -> Result<&'a str, HarnessError> {
    service
        .get(name)
        .and_then(Value::as_str)
        .ok_or_else(|| HarnessError::invalid(format!("service field is not a string: {name}")))
}

/// First character of a feature, guaranteed by validation to exist.
fn letter(service: &Value) -> Result<char, HarnessError> {
    field(service, "feature")?
        .chars()
        .next()
        .ok_or_else(|| HarnessError::invalid("service feature is empty"))
}

/// Sorted unique feature letters.
fn first_letters(services: &[Value]) -> Result<BTreeSet<char>, HarnessError> {
    let mut letters = BTreeSet::new();
    for service in services {
        letters.insert(letter(service)?);
    }
    Ok(letters)
}

/// Render the generated `Cargo.toml`.
fn cargo_manifest(services: &[Value]) -> Result<String, HarnessError> {
    let mut lines: Vec<String> = MANIFEST_HEADER
        .iter()
        .map(|line| (*line).to_string())
        .collect();
    push_all_services(&mut lines, services)?;
    push_service_features(&mut lines, services)?;
    push_dependencies(&mut lines, services)?;
    lines.extend(MANIFEST_TRAILER.iter().map(|line| (*line).to_string()));
    Ok(lines.join("\n"))
}

/// Fixed `Cargo.toml` preamble through the start of `all-services`.
const MANIFEST_HEADER: [&str; 13] = [
    "# Generated by scripts/generate_sdk_catalog.py; exact SDK release pins.",
    "[package]",
    "name = \"inventory-sdk-catalog\"",
    "version.workspace = true",
    "edition.workspace = true",
    "rust-version.workspace = true",
    "license.workspace = true",
    "publish = false",
    "description = \"Pinned catalog of every official AWS service SDK; not collection coverage\"",
    "",
    "[features]",
    "default = []",
    "all-services = [",
];

/// Fixed `Cargo.toml` tail after the dependency table.
const MANIFEST_TRAILER: [&str; 10] = [
    "",
    "[dev-dependencies]",
    "serde_json.workspace = true",
    "sha2.workspace = true",
    "base16ct.workspace = true",
    "toml = \"1.2.1\"",
    "",
    "[lints]",
    "workspace = true",
    "",
];

/// Close `all-services` after naming every feature.
fn push_all_services(lines: &mut Vec<String>, services: &[Value]) -> Result<(), HarnessError> {
    for service in services {
        lines.push(format!("    \"{}\",", field(service, "feature")?));
    }
    lines.push("]".to_string());
    Ok(())
}

/// Per-feature dependency edges and per-letter catalog gates.
fn push_service_features(lines: &mut Vec<String>, services: &[Value]) -> Result<(), HarnessError> {
    for service in services {
        let feature = field(service, "feature")?;
        let name = field(service, "name")?;
        let first = letter(service)?;
        lines.push(format!("{feature} = [\"dep:{name}\", \"catalog-{first}\"]"));
    }
    for first in first_letters(services)? {
        lines.push(format!("catalog-{first} = []"));
    }
    Ok(())
}

/// The `[dependencies]` table with exact pinned optional crates.
fn push_dependencies(lines: &mut Vec<String>, services: &[Value]) -> Result<(), HarnessError> {
    lines.push(String::new());
    lines.push("[dependencies]".to_string());
    for service in services {
        let name = field(service, "name")?;
        let version = field(service, "version")?;
        let features = feature_array(service)?;
        lines.push(format!(
            "{name} = {{ version = \"={version}\", optional = true, \
default-features = false, features = {features} }}"
        ));
    }
    Ok(())
}

/// Python `json.dumps()` rendering of the client feature list.
fn feature_array(service: &Value) -> Result<String, HarnessError> {
    let items = service
        .get("client_features")
        .and_then(Value::as_array)
        .ok_or_else(|| HarnessError::invalid("invalid client feature selection"))?;
    let mut rendered = Vec::with_capacity(items.len());
    for item in items {
        rendered.push(serde_json::to_string(item)?);
    }
    Ok(format!("[{}]", rendered.join(", ")))
}

/// Render the generated `src/lib.rs`.
fn library(document: &Value, services: &[Value]) -> Result<String, HarnessError> {
    let count = document
        .get("service_count")
        .and_then(Value::as_u64)
        .ok_or_else(|| HarnessError::invalid("invalid service count"))?;
    let mut lines = vec![
        "//! Generated SDK catalog. Availability is not implemented collector coverage."
            .to_string(),
        "//! Service crates compile only when their explicit feature is enabled.".to_string(),
        "#![forbid(unsafe_code)]".to_string(),
        "#![deny(unused_must_use)]".to_string(),
        String::new(),
        format!("pub const SERVICE_COUNT: usize = {count};"),
        "pub const SERVICE_MANIFEST_JSON: &str = include_str!(\"../sdk-services.json\");"
            .to_string(),
    ];
    for first in first_letters(services)? {
        lines.push(String::new());
        lines.push(format!("#[cfg(feature = \"catalog-{first}\")]"));
        lines.push(format!("mod services_{first};"));
        lines.push(format!("#[cfg(feature = \"catalog-{first}\")]"));
        lines.push(format!("pub use services_{first}::*;"));
    }
    Ok(format!("{}\n", lines.join("\n")))
}

/// Render one per-letter re-export module.
fn service_library(first: char, services: &[Value]) -> Result<String, HarnessError> {
    let mut lines = vec![format!(
        "//! Generated SDK reexports beginning with {first}."
    )];
    for service in services {
        if letter(service)? != first {
            continue;
        }
        let feature = field(service, "feature")?;
        let crate_name = field(service, "name")?.replace('-', "_");
        lines.push(String::new());
        lines.push(format!("#[cfg(feature = \"{feature}\")]"));
        lines.push(format!("pub use {crate_name} as {feature};"));
    }
    Ok(format!("{}\n", lines.join("\n")))
}

