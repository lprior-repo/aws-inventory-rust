//! Markdown document assembly for the operation coverage report.

use crate::HarnessError;

use super::super::{
    CoverageReport, INVENTORY, OPERATION_ADDITIONS, OPERATION_MATRIX, RECONCILIATION, SAMPLE_LIMIT,
};
use super::percent;

pub(super) fn render(report: &CoverageReport) -> Result<String, HarnessError> {
    let mut out = String::new();
    intro(&mut out, report)?;
    summary(&mut out, report)?;
    evidence(&mut out, report)?;
    provider_generic(&mut out, report);
    services(&mut out, report);
    exercised(&mut out, report);
    excluded(&mut out, report);
    super::additions::render(&mut out, report);
    limits(&mut out, report)?;
    Ok(out)
}

fn intro(out: &mut String, report: &CoverageReport) -> Result<(), HarnessError> {
    let exercised = report.exercised();
    let unexercised = report.unexercised()?;
    let total = report.operations();
    out.push_str("# SDK operation coverage\n\n");
    out.push_str(
        "Generated by `inventory-harness coverage operations --write docs/OPERATION_COVERAGE.md`. \
Do not edit by hand.\n\n## What the counts mean\n\n",
    );
    counts_mean(out, report, exercised, unexercised, total)?;
    Ok(())
}

fn counts_mean(
    out: &mut String,
    report: &CoverageReport,
    exercised: usize,
    unexercised: usize,
    total: usize,
) -> Result<(), HarnessError> {
    out.push_str(&format!(
        "The source universe is every operation in the published SDK inventory \
[{INVENTORY}](../{INVENTORY}): **{total} operations across {} crates**. An operation is \
*exercised* only when an empty-argument `.send()` callsite at the `Cargo.lock`-pinned version \
is proven by the live source scan and has a qualifying recorded emulator outcome at that exact \
SDK version. The separate callsite scan counts lexical invocations, including operations without \
current-version execution evidence. A scan that cannot resolve current source makes the exercised \
count unavailable. Historical outcomes are never transferred to another SDK version. The join \
is on `(crate, version, module)`, never on a module name alone.\n\n",
        report.crates
    ));
    coverage_notes(out, exercised, unexercised, total, report)
}

fn coverage_notes(
    out: &mut String,
    exercised: usize,
    unexercised: usize,
    total: usize,
    report: &CoverageReport,
) -> Result<(), HarnessError> {
    out.push_str(&format!(
        "**This document does not claim that all operations are invoked. {exercised} of {total} \
({}) are exercised; {unexercised} are not.** An unexercised operation lacks qualifying \
current-version execution evidence; it may still have a collector callsite or historical outcome.\n\n",
        percent(exercised, total)?
    ));
    provider_notes(out, report);
    Ok(())
}

fn provider_notes(out: &mut String, report: &CoverageReport) {
    out.push_str(&format!(
        "Cloud Control `ListResources` and `GetResource` are **provider-generic**: they count \
**once each**, not once per configured resource type. The provider-generic portion is \
{} exercised operation(s); typed native collector coverage is {} operation(s). Descriptor \
breadth (for example the 421 executable resource types) is resource-type coverage, never \
operation coverage.\n\n",
        report.provider_generic_exercised, report.typed_native_exercised
    ));
    if !report.additions.is_empty() {
        out.push_str(&format!(
            "A further {} reviewed additive operation(s) are listed separately below; they are \
not exercised and carry no emulator outcome.\n\n",
            report.additions.len()
        ));
    }
}

fn summary(out: &mut String, report: &CoverageReport) -> Result<(), HarnessError> {
    summary_start(out, report)?;
    summary_tail(out, report)
}

fn summary_start(out: &mut String, report: &CoverageReport) -> Result<(), HarnessError> {
    let exercised = report.exercised();
    let total = report.operations();
    out.push_str("## Summary\n\n| Measure | Count |\n| --- | ---: |\n");
    out.push_str(&format!(
        "| Operations in the published inventory | {total} |\n"
    ));
    out.push_str(&format!(
        "| SDK crates / services | {} / {} |\n",
        report.crates,
        report.services.len()
    ));
    out.push_str(&format!(
        "| Exercised | {exercised} ({}) |\n| Unexercised | {} |\n",
        percent(exercised, total)?,
        report.unexercised()?
    ));
    Ok(())
}

fn summary_tail(out: &mut String, report: &CoverageReport) -> Result<(), HarnessError> {
    out.push_str(&format!(
        "| Provider-generic exercised (`cloudcontrol.ListResources`, `GetResource`) | {} of {} |\n\
| Typed native exercised | {} |\n| Excluded by recorded `sdk_decode_failure` | {} |\n",
        report.provider_generic_exercised,
        report.provider_generic_total,
        report.typed_native_exercised,
        report.excluded.len()
    ));
    if !report.additions.is_empty() {
        out.push_str(&format!(
            "| Reviewed additive (unexercised) | {} |\n",
            report.additions.len()
        ));
    }
    out.push('\n');
    Ok(())
}

fn evidence(out: &mut String, report: &CoverageReport) -> Result<(), HarnessError> {
    out.push_str("## Evidence sources and exact digests\n\n");
    out.push_str(
        "| Source | Path | SHA-256 or status | What it supplies |\n| --- | --- | --- | --- |\n",
    );
    out.push_str(&format!(
        "| Published SDK inventory | `{INVENTORY}` | `{}` | `(crate, version, module, api_operation)` universe |\n",
        report.inventory_sha256
    ));
    evidence_rows(out, report);
    status_rows(out, report);
    Ok(())
}

fn evidence_rows(out: &mut String, report: &CoverageReport) {
    out.push_str(&format!(
        "| Current callsite scan | `crates/aws/src` | `{}` | {} files, {} empty sends; `{}` |\n",
        report.scan_sha256.as_deref().unwrap_or("not produced"),
        report.scan_files,
        report.scan_callsites,
        report.scan_status
    ));
    out.push_str(&format!(
        "| Recorded emulator outcomes | `{OPERATION_MATRIX}` | `{}` | {} statuses from `{}`; {} of {} reviewed source files changed |\n",
        report.matrix_sha256,
        report.status_count,
        report.matrix_execution,
        report.reviewed_changed,
        report.reviewed_files
    ));
    additions_row(out, report);
}

fn additions_row(out: &mut String, report: &CoverageReport) {
    if report.additions_status == "absent" {
        return;
    }
    out.push_str(&format!(
        "| Reviewed additive operations | `{OPERATION_ADDITIONS}` | `{}` | {} operations from \
{} callsites; bound historical matrix `{}`; unexercised |\n",
        report.additions_sha256.as_deref().unwrap_or("not produced"),
        report.additions.len(),
        report
            .additions
            .iter()
            .map(|row| row.sites.len())
            .sum::<usize>(),
        report.additions_matrix_sha256
    ));
}

fn status_rows(out: &mut String, report: &CoverageReport) {
    out.push_str(&format!(
        "| Newest reconciliation receipt | `{RECONCILIATION}` | {} | `{}` |\n",
        report.reconciliation_sha256.as_deref().unwrap_or("absent"),
        report.reconciliation_status
    ));
    out.push_str(&format!(
        "\nThe applied status source for this report is `{}`.\n\n",
        report.status_source
    ));
    out.push_str(
        "Exact commands (run from the repository root):\n\n```bash\n\
inventory-harness coverage operations\n\
inventory-harness coverage operations --format json\n\
inventory-harness coverage operations --write docs/OPERATION_COVERAGE.md\n\
inventory-harness coverage operations --check\n```\n\n",
    );
}

fn provider_generic(out: &mut String, report: &CoverageReport) {
    out.push_str(
        "## Provider-generic Cloud Control operations\n\n| Service | SDK method | API operation | Emulator status | Evidence |\n| --- | --- | --- | --- | --- |\n",
    );
    for row in report.exercised.iter().filter(|row| row.provider_generic) {
        out.push_str(&format!(
            "| `{}` | `{}` | `{}` | {} | {} |\n",
            row.service,
            row.module,
            row.api_operation,
            row.status.as_deref().unwrap_or("not recorded"),
            row.evidence.join(", ")
        ));
    }
    out.push_str(&format!(
        "\nThese two operations serve every descriptor type; configured types are not counted as \
operations. The provider-generic total in the inventory is {}.\n\n## Coverage by service\n\n\
| Service | SDK crate | Operations | Exercised | Unexercised |\n| --- | --- | ---: | ---: | ---: |\n",
        report.provider_generic_total
    ));
}

fn services(out: &mut String, report: &CoverageReport) {
    for row in &report.services {
        out.push_str(&format!(
            "| `{}` | `{}` | {} | {} | {} |\n",
            row.service,
            row.crate_name,
            row.total,
            row.exercised,
            row.total.saturating_sub(row.exercised)
        ));
    }
}

fn exercised(out: &mut String, report: &CoverageReport) {
    out.push_str(
        "\n## Exercised operations\n\n\
| Service | SDK method | API operation | Emulator status | Evidence |\n| --- | --- | --- | --- | --- |\n",
    );
    for row in &report.exercised {
        out.push_str(&format!(
            "| `{}` | `{}` | `{}` | {} | {} |\n",
            row.service,
            row.module,
            row.api_operation,
            *row.status.as_deref().get_or_insert("not recorded"),
            row.evidence.join(", ")
        ));
    }
    out.push('\n');
}

fn excluded(out: &mut String, report: &CoverageReport) {
    if report.excluded.is_empty() {
        return;
    }
    out.push_str(
        "## Excluded by recorded evidence\n\nThese callsites exist, but the recorded \
reconciliation classifies them as `sdk_decode_failure`, so they are not counted as \
exercised.\n\n| Service | SDK method | API operation | Status | Source |\n\
| --- | --- | --- | --- | --- |\n",
    );
    for row in &report.excluded {
        out.push_str(&format!(
            "| `{}` | `{}` | `{}` | `{}` | `{}` |\n",
            row.service, row.module, row.api_operation, row.status, row.source
        ));
    }
    out.push('\n');
}

fn limits(out: &mut String, report: &CoverageReport) -> Result<(), HarnessError> {
    out.push_str(&format!(
        "## Unexercised operations\n\n{} operations lack qualifying current-version execution \
evidence. The JSON report samples the first {SAMPLE_LIMIT} in sorted order in \
`unexercised_sample`; the sample is not a complete listing. Use `inventory-harness coverage \
operations` for the full service rollup.\n\n## Limits\n\n\
- A lexical callsite proves the collector invokes the operation; it does not prove every \
branch, request shape, IAM permission, or live AWS response.\n\
- The emulator status records the pinned local emulator outcome, not live AWS behavior.\n\
- Cloud Control descriptor breadth is resource-type coverage, not SDK operation coverage.\n\
- This report does not establish that every exercised operation succeeded.\n\
- The inventory counts every cached generated crate version, not just active versions. \
Rows from versions not pinned by `Cargo.lock` remain unexercised; historical execution \
outcomes do not establish that an upgraded SDK version was exercised.\n",
        report.unexercised()?
    ));
    Ok(())
}
