//! Explicit SDK probes for branches a normal populated emulator scan may skip.
//!
//! DescribeRegions cannot drive a multi-region scan against one emulator because
//! the emulator does not isolate region state. HeadBucket is a fallback when S3
//! ListBuckets omits BucketRegion, which this emulator normally supplies. These
//! probes are reported separately from production collector-path coverage.
//! Resource Explorer probes also test downstream operations when an upstream
//! discovery response cannot be decoded; errors remain errors in the report.
#![forbid(unsafe_code)]

use std::io::Write;
use std::time::Duration;

use aws_config::{BehaviorVersion, retry::RetryConfig};
use aws_smithy_types::timeout::TimeoutConfig;
use aws_types::region::Region;
use serde_json::{Value, json};

type Result<T> = std::result::Result<T, Box<dyn std::error::Error>>;

fn main() -> Result<std::process::ExitCode> {
    let endpoint = validate_endpoint(&std::env::var("AWS_ENDPOINT_URL")?)?;
    let bucket = std::env::var("AWS_EMULATOR_BUCKET")?;
    if !bucket.starts_with("inventory-emulator-") || bucket.len() > 63 {
        return Err("AWS_EMULATOR_BUCKET must name a bounded inventory-emulator fixture".into());
    }
    if std::env::var("AWS_EC2_METADATA_DISABLED")?.as_str() != "true"
        || std::env::var_os("AWS_ACCESS_KEY_ID").is_some()
        || std::env::var_os("AWS_SECRET_ACCESS_KEY").is_some()
        || std::env::var_os("AWS_SESSION_TOKEN").is_some()
    {
        return Err(
            "emulator probes require isolated generated credentials and disabled IMDS".into(),
        );
    }
    let access_key = std::env::var("INVENTORY_EMULATOR_ACCESS_KEY_ID")?;
    let secret = std::env::var("INVENTORY_EMULATOR_SECRET_ACCESS_KEY")?;
    if !access_key.starts_with("EMULATOR")
        || access_key.len() > 128
        || secret.is_empty()
        || secret.len() > 256
    {
        return Err(
            "probe credentials must be the bounded keys generated by this emulator run".into(),
        );
    }
    let credentials =
        aws_credential_types::Credentials::new(access_key, secret, None, None, "emulator-probe");
    let view = std::env::var("AWS_EMULATOR_VIEW_ARN")?;
    if !view.starts_with("arn:aws:resource-explorer-2:us-east-1:000000000000:view/")
        || view.len() > 2_048
    {
        return Err("AWS_EMULATOR_VIEW_ARN must name the scoped emulator view fixture".into());
    }
    let runtime = tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()?;
    let result = runtime.block_on(async {
        tokio::time::timeout(
            Duration::from_secs(90),
            probe(endpoint, bucket, view, credentials),
        )
        .await
    })??;
    let mut output = std::io::stdout().lock();
    serde_json::to_writer_pretty(&mut output, &result)?;
    output.write_all(b"\n")?;
    Ok(
        if result.get("status").and_then(Value::as_str) == Some("partial") {
            std::process::ExitCode::from(2)
        } else {
            std::process::ExitCode::SUCCESS
        },
    )
}

fn validate_endpoint(value: &str) -> Result<String> {
    let port = value
        .strip_prefix("https://127.0.0.1:")
        .ok_or("emulator endpoint must use https://127.0.0.1 and an explicit port")?;
    if port.parse::<u16>()? == 0 {
        return Err("emulator endpoint port must be nonzero".into());
    }
    Ok(value.to_owned())
}

async fn probe(
    endpoint: String,
    bucket: String,
    view: String,
    credentials: aws_credential_types::Credentials,
) -> Result<Value> {
    let config = aws_config::defaults(BehaviorVersion::latest())
        .credentials_provider(credentials)
        .region(Region::new("us-east-1"))
        .endpoint_url(endpoint)
        .retry_config(RetryConfig::standard().with_max_attempts(1))
        .timeout_config(
            TimeoutConfig::builder()
                .operation_timeout(Duration::from_secs(10))
                .operation_attempt_timeout(Duration::from_secs(10))
                .build(),
        )
        .load()
        .await;
    let identity = aws_sdk_sts::Client::new(&config)
        .get_caller_identity()
        .send()
        .await?;
    if identity.account() != Some("000000000000") {
        return Err("emulator account identity mismatch".into());
    }
    let regions = aws_sdk_ec2::Client::new(&config)
        .describe_regions()
        .all_regions(false)
        .send()
        .await?;
    if !regions
        .regions()
        .iter()
        .any(|region| region.region_name() == Some("us-east-1"))
    {
        return Err("DescribeRegions did not return the fixture region".into());
    }
    let bucket = aws_sdk_s3::Client::new(&config)
        .head_bucket()
        .bucket(bucket)
        .expected_bucket_owner("000000000000")
        .send()
        .await?;
    if bucket.bucket_region() != Some("us-east-1") {
        return Err("HeadBucket returned an unexpected fixture bucket region".into());
    }
    let explorer = probe_explorer(&config, &view).await;
    let status = if explorer.iter().all(|value| {
        value.get("sdk_decoded").and_then(Value::as_bool) == Some(true)
            && value.get("assertions_passed").and_then(Value::as_bool) == Some(true)
    }) {
        "complete"
    } else {
        "partial"
    };
    Ok(json!({
        "status":status, "scope":"explicit_sdk_branch_probes",
        "assertions":[
            {"operation":"sts:GetCallerIdentity","account":"000000000000"},
            {"operation":"ec2:DescribeRegions","contains_fixture_region":true,"region_count":regions.regions().len()},
            {"operation":"s3:HeadBucket","bucket_region":"us-east-1","expected_owner_applied":true}
        ],
        "production_branch_reached":false,
        "resource_explorer":explorer
    }))
}

async fn probe_explorer(config: &aws_types::SdkConfig, view: &str) -> Vec<Value> {
    let client = aws_sdk_resourceexplorer2::Client::new(config);
    let index = probe_result(
        "resource-explorer-2:GetIndex",
        client.get_index().send().await,
        |output| {
            (
                output.arn().is_some_and(|arn| {
                    arn.starts_with("arn:aws:resource-explorer-2:us-east-1:000000000000:index/")
                }) && output
                    .state()
                    .is_some_and(|state| state.as_str() == "ACTIVE"),
                json!({"arn":output.arn(),"state":output.state().map(|state|state.as_str())}),
            )
        },
    );
    let default = probe_result(
        "resource-explorer-2:GetDefaultView",
        client.get_default_view().send().await,
        |output| {
            (
                output.view_arn() == Some(view),
                json!({"view_arn":output.view_arn(),"matches_fixture":output.view_arn()==Some(view)}),
            )
        },
    );
    let views = probe_result(
        "resource-explorer-2:ListViews",
        client.list_views().max_results(1).send().await,
        |output| {
            (
                !output.views().is_empty()
                    && output.views().iter().all(|arn| {
                        arn.starts_with("arn:aws:resource-explorer-2:us-east-1:000000000000:view/")
                    }),
                json!({"views":output.views(),"has_next_token":output.next_token().is_some()}),
            )
        },
    );
    let detail = probe_result(
        "resource-explorer-2:GetView",
        client.get_view().view_arn(view).send().await,
        |output| {
            (
                output
                    .view()
                    .is_some_and(|detail| detail.view_arn() == Some(view)),
                json!({"view_present":output.view().is_some()}),
            )
        },
    );
    let resources = probe_result(
        "resource-explorer-2:ListResources",
        client
            .list_resources()
            .view_arn(view)
            .max_results(1)
            .send()
            .await,
        |output| {
            (
                !output.resources().is_empty(),
                json!({"resource_count":output.resources().len(),"has_next_token":output.next_token().is_some()}),
            )
        },
    );
    vec![index, default, views, detail, resources]
}

fn probe_result<T, E: std::error::Error + 'static>(
    operation: &str,
    result: std::result::Result<T, aws_sdk_sts::error::SdkError<E>>,
    summarize: impl FnOnce(&T) -> (bool, Value),
) -> Value {
    match result {
        Ok(value) => {
            let (passed, summary) = summarize(&value);
            json!({"operation":operation,"sdk_decoded":true,"assertions_passed":passed,"response":summary})
        }
        Err(error) => {
            let http_status = error
                .raw_response()
                .map(|response| response.status().as_u16());
            let kind = match (&error, http_status) {
                (aws_sdk_sts::error::SdkError::ServiceError(_), Some(200..=299)) => {
                    "success_response_rejected"
                }
                (aws_sdk_sts::error::SdkError::ResponseError(_), Some(200..=299)) => {
                    "response_decode_failure"
                }
                (_, None) => "transport_or_construction_error",
                _ => "service_error",
            };
            let mut chain = Vec::new();
            let mut current: Option<&dyn std::error::Error> = Some(&error);
            for _ in 0..8 {
                let Some(error) = current else { break };
                chain.push(error.to_string().chars().take(512).collect::<String>());
                current = error.source();
            }
            json!({"operation":operation,"sdk_decoded":false,"sdk_error_kind":kind,"http_status":http_status,"error_chain":chain})
        }
    }
}

#[cfg(test)]
mod tests {
    use super::validate_endpoint;

    #[test]
    fn probes_reject_nonlocal_or_ambiguous_endpoints() {
        for endpoint in [
            "https://sts.amazonaws.com",
            "http://127.0.0.1:9297",
            "https://localhost:9297",
            "https://127.0.0.1:0",
            "https://127.0.0.1:9297/path",
            "https://127.0.0.1:9297@aws.example",
        ] {
            assert!(validate_endpoint(endpoint).is_err());
        }
        assert!(validate_endpoint("https://127.0.0.1:9297").is_ok());
    }
}
