//! Reproduce the checked-in Cloud Control views from the pinned resource catalog.
//! This development tool performs no AWS calls and needs no service SDK feature.
use std::collections::BTreeSet;
use std::path::PathBuf;

use serde_json::Value;

type Result<T, E = Box<dyn std::error::Error>> = std::result::Result<T, E>;

const PARENT_ADDITIONS: [&str; 3] = [
    "AWS::AppConfig::ExperimentDefinition",
    "AWS::EKS::AccessEntry",
    "AWS::EKS::PodIdentityAssociation",
];

fn main() -> Result<()> {
    let arguments: Vec<String> = std::env::args().skip(1).take(2).collect();
    let check = match arguments.as_slice() {
        [] => false,
        [flag] if flag == "--check" => true,
        _ => return Err("usage: resource_views [--check]".into()),
    };
    let manifest: Value =
        serde_json::from_str(include_str!("../../../catalog/cloudcontrol-resources.json"))?;
    let legacy_names: BTreeSet<String> =
        serde_json::from_str(include_str!("../../../catalog/cloudcontrol-v04-types.json"))?;
    if legacy_names.len() != 200 {
        return Err("the schema-v4 baseline must contain exactly 200 types".into());
    }
    let resources = manifest
        .get("resource_types")
        .and_then(Value::as_array)
        .ok_or("missing resource_types")?;
    let (legacy, additional): (Vec<Value>, Vec<Value>) = resources.iter().cloned().partition(|r| {
        r.get("type_name")
            .and_then(Value::as_str)
            .is_some_and(|n| legacy_names.contains(n))
    });
    if legacy.len() != legacy_names.len() {
        return Err("current catalog removed a schema-v4 resource type".into());
    }
    let old_sql = generate(&serde_json::json!({"resource_types":legacy}))?;
    let mut new_sql = generate(&serde_json::json!({"resource_types":additional}))?;
    new_sql.push_str("PRAGMA user_version = 5;\n");
    publish("003_cloudcontrol_views.sql", &old_sql, check)?;
    publish("005_cloudcontrol_expansion.sql", &new_sql, check)?;
    let parents: Value = serde_json::from_str(include_str!(
        "../../../catalog/cloudcontrol-parent-resources.json"
    ))?;
    let parent_rows = parents
        .get("resource_types")
        .and_then(Value::as_array)
        .ok_or("missing parent resource_types")?;
    let additions: Vec<Value> = parent_rows
        .iter()
        .filter(|row| {
            row.get("type_name")
                .and_then(Value::as_str)
                .is_some_and(|name| PARENT_ADDITIONS.contains(&name))
        })
        .cloned()
        .collect();
    if additions.len() != PARENT_ADDITIONS.len() {
        return Err("parent view addition is missing from the catalog".into());
    }
    let base: Vec<Value> = parent_rows
        .iter()
        .filter(|row| {
            row.get("type_name")
                .and_then(Value::as_str)
                .is_none_or(|name| !PARENT_ADDITIONS.contains(&name))
        })
        .cloned()
        .collect();
    let mut parent_sql = generate(&serde_json::json!({"resource_types":base}))?;
    parent_sql.push_str("PRAGMA user_version = 6;\n");
    publish("006_cloudcontrol_parents.sql", &parent_sql, check)?;
    let mut addition_sql = generate(&serde_json::json!({"resource_types":additions}))?;
    addition_sql.push_str("PRAGMA user_version = 13;\n");
    publish(
        "013_cloudcontrol_parent_additions.sql",
        &addition_sql,
        check,
    )?;
    println!(
        "Cloud Control SQL views {}",
        if check { "verified" } else { "generated" }
    );
    Ok(())
}

fn publish(filename: &str, generated: &str, check: bool) -> Result<()> {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("sql")
        .join(filename);
    if check {
        if std::fs::metadata(&path)?.len() > 4_194_304 {
            return Err("generated SQL file exceeds bound".into());
        }
        if std::fs::read_to_string(&path)? != generated {
            return Err("Cloud Control SQL views differ from the catalog; regenerate them".into());
        }
    } else {
        std::fs::write(path, generated)?;
    }
    Ok(())
}

fn generate(manifest: &Value) -> Result<String> {
    let resources = manifest
        .get("resource_types")
        .and_then(Value::as_array)
        .ok_or("missing resource_types")?;
    if resources.len() > 512 {
        return Err("resource type count outside bounds".into());
    }
    let mut sql = String::from(
        "-- Generated by cargo run -p inventory-engine --example resource_views.\n\
         -- Source-specific views preserve Cloud Control fields even when direct observations win.\n\n",
    );
    let mut views = BTreeSet::new();
    for resource in resources {
        let name = text(resource, "view_name")?;
        if !identifier(name) || !name.starts_with("aws_cc_") || !views.insert(name) {
            return Err("invalid or duplicate Cloud Control view name".into());
        }
        let type_name = text(resource, "type_name")?;
        if type_name.len() > 256
            || !type_name.starts_with("AWS::")
            || !type_name
                .bytes()
                .all(|byte| byte.is_ascii_alphanumeric() || byte == b':')
        {
            return Err("invalid CloudFormation type name".into());
        }
        let columns = resource
            .get("columns")
            .and_then(Value::as_array)
            .ok_or("missing provider columns")?;
        if columns.len() > 200 {
            return Err("provider column count exceeds bound".into());
        }
        let mut names = BTreeSet::from([
            "scan_id",
            "id",
            "arn",
            "account_id",
            "region",
            "kind",
            "name",
            "source",
            "source_priority",
            "observed_at",
            "resource_json",
            "properties",
            "tags",
            "cloudformation_type",
            "resource_identifier",
            "provider_properties",
        ]);
        let mut statement = format!("CREATE VIEW {name} AS\nSELECT r.*");
        for column in columns {
            let alias = text(column, "name")?;
            if !identifier(alias) || !names.insert(alias) {
                return Err(format!(
                    "invalid or duplicate provider column name: {type_name}.{alias}"
                )
                .into());
            }
            let field = text(column, "pointer")?
                .strip_prefix('/')
                .ok_or("provider column is not a JSON pointer")?;
            // The generated catalog selects top-level AWS schema properties.
            // Restrict both identifiers and path components rather than putting
            // arbitrary catalog SQL or expressions into the migration.
            if field.is_empty()
                || field.len() > 256
                || !field
                    .bytes()
                    .all(|byte| byte.is_ascii_alphanumeric() || byte == b'_')
            {
                return Err("unsupported provider property path".into());
            }
            statement.push_str(&format!(
                ",\n       json_extract(r.provider_properties, '$.{field}') AS \"{alias}\""
            ));
        }
        statement.push_str(&format!(
            "\nFROM aws_cloudcontrol_resource r WHERE cloudformation_type = '{type_name}';\n\n"
        ));
        if statement.len() > 65_536 {
            return Err("generated statement exceeds SQLite SQL bound".into());
        }
        sql.push_str(&statement);
        if sql.len() > 4_194_304 {
            return Err("generated SQL exceeds bound".into());
        }
    }
    Ok(sql)
}

fn text<'a>(value: &'a Value, field: &str) -> Result<&'a str> {
    value
        .get(field)
        .and_then(Value::as_str)
        .filter(|value| !value.is_empty())
        .ok_or_else(|| format!("missing {field}").into())
}

fn identifier(value: &str) -> bool {
    !value.is_empty()
        && value.len() <= 256
        && value
            .bytes()
            .next()
            .is_some_and(|byte| byte.is_ascii_lowercase())
        && value
            .bytes()
            .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'_')
}
