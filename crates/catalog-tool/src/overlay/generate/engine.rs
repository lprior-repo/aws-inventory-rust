use super::{Failure, output::Report, render, service};
use crate::{
    classes::DenyList,
    endpoints::{self, DerivedEndpoint, ServiceClass},
    overlay::{Scope, ServiceOverlay, check::orchestration},
    plans::{Model, Vocabulary},
};
use serde_json::Value;
use std::{
    collections::{BTreeMap, BTreeSet},
    path::Path,
};

pub struct Generator {
    values: BTreeMap<String, Value>,
    vocabulary: Vocabulary,
    scopes: BTreeMap<String, Scope>,
}

#[derive(Default)]
pub struct Generated {
    pub(super) files: BTreeMap<String, String>,
    pub(super) report: String,
    policies: Vec<ServiceOverlay>,
}

impl Generated {
    pub fn files(&self) -> &BTreeMap<String, String> {
        &self.files
    }

    pub fn report(&self) -> &str {
        &self.report
    }

    pub fn policies(&self) -> &[ServiceOverlay] {
        &self.policies
    }
}

impl Generator {
    pub fn read(source: &Path) -> Result<Self, Failure> {
        let values = orchestration::read_model_values(source)?;
        let mut vocabulary = Vocabulary::default();
        for (service, value) in &values {
            vocabulary.record(&Model::parse(value, service)?)?;
        }
        let scopes = endpoints::verified_endpoints(source)?
            .into_iter()
            .filter_map(|(service, endpoint)| {
                scope(endpoint.endpoint()).map(|scope| (service, scope))
            })
            .collect();
        Ok(Self {
            values,
            vocabulary,
            scopes,
        })
    }

    pub fn values(&self) -> &BTreeMap<String, Value> {
        &self.values
    }

    pub fn generate(
        &self,
        services: &BTreeSet<String>,
        deny: &DenyList<'_>,
    ) -> Result<Generated, Failure> {
        if services.len() > crate::overlay::directory::MAX_FILES {
            return Err("generated service limit".into());
        }
        let deny = deny.with_builtin();
        let mut generated = Generated::default();
        let mut report = Report::default();
        let mut bytes = 0_usize;
        for name in services {
            let entry = self.service(name, &deny)?;
            report.service(name, &entry)?;
            add(&mut generated, name, entry.policy, &mut bytes)?;
        }
        generated.report = report.finish()?;
        Ok(generated)
    }

    fn service(
        &self,
        name: &str,
        deny: &DenyList<'_>,
    ) -> Result<service::GeneratedService, Failure> {
        let value = self
            .values
            .get(name)
            .ok_or_else(|| format!("unknown service {name}"))?;
        let model = Model::parse(value, name)?;
        Ok(service::generate(
            name,
            &model,
            self.scopes.get(name).copied(),
            &self.vocabulary,
            deny,
        )?)
    }

    pub fn check(
        &self,
        policies: &[ServiceOverlay],
        deny: &DenyList<'_>,
    ) -> Result<crate::overlay::CheckedOverlays, Failure> {
        Ok(orchestration::check_model_policies(
            &self.values,
            policies,
            deny,
        )?)
    }
}

fn add(
    generated: &mut Generated,
    name: &str,
    policy: ServiceOverlay,
    bytes: &mut usize,
) -> Result<(), Failure> {
    let text = render::render(&policy)?;
    *bytes = bytes
        .checked_add(text.len())
        .ok_or("generated byte count overflow")?;
    if *bytes > 67_108_864 {
        return Err("generated files exceed 64 MiB".into());
    }
    generated.files.insert(name.to_owned(), text);
    generated.policies.try_reserve(1)?;
    generated.policies.push(policy);
    Ok(())
}

fn scope(endpoint: &DerivedEndpoint) -> Option<Scope> {
    match endpoint {
        DerivedEndpoint::Resolved {
            class: ServiceClass::Global,
            ..
        } => Some(Scope::Account),
        DerivedEndpoint::Resolved {
            class: ServiceClass::Regional,
            ..
        } => Some(Scope::Region),
        _ => None,
    }
}
